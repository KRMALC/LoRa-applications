static uint8_t crc8(const uint8_t *d, uint8_t n)
{
  uint8_t c = 0x00;
  while (n--)
  {
    c ^= *d++;
    for (uint8_t i = 0; i < 8; i++)
      c = (c & 0x80) ? (uint8_t)((c << 1) ^ 0x07) : (uint8_t)(c << 1);
  }
  return c;
}

static void motor_pinleri(GPIO_PinState in1, GPIO_PinState in2)
{
  HAL_GPIO_WritePin(MOTOR_IN1_GPIO_Port, MOTOR_IN1_Pin, in1);
  HAL_GPIO_WritePin(MOTOR_IN2_GPIO_Port, MOTOR_IN2_Pin, in2);
}

static void motor_ayarla(uint8_t yeni)
{
  if (yeni == motor_durumu) return;

  /* Yön değişirken önce kısa dur */
  if (motor_durumu != MOTOR_DUR && yeni != MOTOR_DUR)
  {
    motor_pinleri(GPIO_PIN_RESET, GPIO_PIN_RESET);
    HAL_Delay(200);
  }

  if (yeni == MOTOR_ILERI)     motor_pinleri(GPIO_PIN_SET,   GPIO_PIN_RESET);
  else if (yeni == MOTOR_GERI) motor_pinleri(GPIO_PIN_RESET, GPIO_PIN_SET);
  else                         motor_pinleri(GPIO_PIN_RESET, GPIO_PIN_RESET);

  motor_durumu = yeni;
}

static uint8_t komut_uygula(uint8_t cmd, uint8_t veri)
{
  (void)veri;   /* ileride hız (PWM) için kullanılacak */
  switch (cmd)
  {
    case CMD_ILERI: motor_ayarla(MOTOR_ILERI); return ST_OK;
    case CMD_GERI:  motor_ayarla(MOTOR_GERI);  return ST_OK;
    case CMD_DUR:   motor_ayarla(MOTOR_DUR);   return ST_OK;
    case CMD_DURUM:                            return ST_OK;
    default:                                   return ST_BILINMEYEN;
  }
}

static void ack_gonder(uint8_t seq, uint8_t durum_kodu)
{
  uint8_t p[PKT_UZUNLUK];
  p[0] = PKT_ACK_BASLIK;
  p[1] = seq;
  p[2] = durum_kodu;
  p[3] = motor_durumu;
  p[4] = crc8(&p[1], 3);
  HAL_UART_Transmit(&huart2, p, PKT_UZUNLUK, 100);
}

static int rb_al(uint8_t *b)
{
  if (rb_bas == rb_son) return 0;
  *b = rb[rb_son];
  rb_son = (rb_son + 1) % RB_BOYUT;
  return 1;
}

/* Gelen baytları paket paket çözer; ana döngüde sürekli çağrılır */
static void paket_isle(void)
{
  static uint8_t  buf[PKT_UZUNLUK];
  static uint8_t  idx = 0;
  static uint32_t son_bayt_zamani = 0;
  uint8_t b;

  while (rb_al(&b))
  {
    uint32_t simdi = HAL_GetTick();
    if (idx > 0 && (simdi - son_bayt_zamani) > PAKET_ARA_MS) idx = 0;  /* yarım paketi at */
    son_bayt_zamani = simdi;

    if (idx == 0 && b != PKT_CMD_BASLIK) continue;   /* başlığı bekle */
    buf[idx++] = b;
    if (idx < PKT_UZUNLUK) continue;
    idx = 0;

    if (crc8(&buf[1], 3) != buf[4])
    {
      ist_crc_hata++;          /* bozuk paket: cevap verme, ESP32 tekrar gönderecek */
      continue;
    }

    uint8_t seq = buf[1];
    if (son_seq_gecerli && seq == son_seq)
    {
      /* Aynı paket tekrar geldi (bizim ACK kaybolmuş). Komutu tekrar
         uygulama, sadece ACK'yi tekrar gönder. */
      ist_tekrar++;
      ack_gonder(seq, son_durum_kodu);
      continue;
    }

    ist_paket++;
    son_durum_kodu  = komut_uygula(buf[2], buf[3]);
    son_seq         = seq;
    son_seq_gecerli = 1;
    ack_gonder(seq, son_durum_kodu);
  }
}

/* Her bayt geldiğinde HAL burayı çağırır: baytı tampona yaz, sonrakini bekle */
void HAL_UART_RxCpltCallback(UART_HandleTypeDef *huart)
{
  if (huart->Instance == USART2)
  {
    uint16_t sonraki = (rb_bas + 1) % RB_BOYUT;
    if (sonraki != rb_son)          /* tampon doluysa baytı at */
    {
      rb[rb_bas] = rx_byte;
      rb_bas = sonraki;
    }
    HAL_UART_Receive_IT(&huart2, &rx_byte, 1);
  }
}

void HAL_UART_ErrorCallback(UART_HandleTypeDef *huart)
{
  if (huart->Instance == USART2)
    HAL_UART_Receive_IT(&huart2, &rx_byte, 1);
}

